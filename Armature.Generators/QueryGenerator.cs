
using System;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace Armature.Generators;

[Generator]
public sealed class QueryGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(static output =>
        {
            for (var arity = 1; arity <= 8; arity++)
            {
                output.AddSource(
                    $"Query{arity}.g.cs",
                    SourceText.From(Generate(arity), Encoding.UTF8)
                );
            }
        });
    }

    private static string Generate(int arity)
    {
        var sb = new StringBuilder();

        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("using System;");
        sb.AppendLine("namespace Armature.Scene;");
        sb.AppendLine();

        var types = new string[arity];

        for (var i = 0; i < arity; i++)
            types[i] = $"T{i + 1}";

        var genericTypes = string.Join(", ", types);

        // QueryItem<T...>
        sb.AppendLine(
            $"public readonly ref struct QueryItem<{genericTypes}>"
        );
        AppendConstraints(sb, arity);
        sb.AppendLine("{");

        for (var i = 0; i < arity; i++)
            sb.AppendLine($"    public readonly ref T{i + 1} C{i + 1};");

        sb.AppendLine();
        sb.AppendLine(
            $"    public QueryItem(Entity entity, {string.Join(", ", CreateParameters(arity))})"
        );
        sb.AppendLine("    {");
        sb.AppendLine("        Entity = entity;");

        for (var i = 0; i < arity; i++)
            sb.AppendLine($"        C{i + 1} = ref c{i + 1};");

        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    public readonly Entity Entity;");
        sb.AppendLine("}");
        sb.AppendLine();

        // Query<T...>
        sb.AppendLine(
            $"public readonly ref struct Query<{genericTypes}>"
        );
        AppendConstraints(sb, arity);
        sb.AppendLine("{");

        for (var i = 0; i < arity; i++)
            sb.AppendLine(
                $"    private readonly ComponentPool<T{i + 1}> _p{i + 1};"
            );

        sb.AppendLine();

        sb.AppendLine(
            $"    public Query({string.Join(", ", CreatePoolParameters(arity))})"
        );
        sb.AppendLine("    {");

        for (var i = 0; i < arity; i++)
            sb.AppendLine($"        _p{i + 1} = p{i + 1};");

        sb.AppendLine("    }");

        sb.AppendLine();

        sb.AppendLine(
            $"    public Enumerator GetEnumerator() => new({string.Join(", ", CreatePoolArguments(arity))});"
        );

        sb.AppendLine();

        // MaxCount
        sb.AppendLine(
            $"    public int MaxCount => {CreateMinCountExpression(arity)};"
        );

        sb.AppendLine();

        // Enumerator
        sb.AppendLine("    public ref struct Enumerator");
        sb.AppendLine("    {");

        for (var i = 0; i < arity; i++)
            sb.AppendLine(
                $"        private readonly ComponentPool<T{i + 1}> _p{i + 1};"
            );

        sb.AppendLine("        private readonly int _driver;");
        sb.AppendLine("        private int _index;");

        for (var i = 0; i < arity; i++)
            sb.AppendLine($"        private int _i{i + 1};");

        sb.AppendLine("        private Entity _entity;");
        sb.AppendLine();

        // Enumerator constructor
        sb.AppendLine(
            $"        public Enumerator({string.Join(", ", CreatePoolParameters(arity))})"
        );
        sb.AppendLine("        {");

        for (var i = 0; i < arity; i++)
            sb.AppendLine($"            _p{i + 1} = p{i + 1};");

        sb.AppendLine();
        sb.AppendLine("            _driver = 1;");
        sb.AppendLine("            var min = p1.Count;");

        for (var i = 1; i < arity; i++)
        {
            sb.AppendLine(
                $"            if (p{i + 1}.Count < min)"
            );
            sb.AppendLine("            {");
            sb.AppendLine($"                _driver = {i + 1};");
            sb.AppendLine($"                min = p{i + 1}.Count;");
            sb.AppendLine("            }");
        }

        sb.AppendLine();
        sb.AppendLine("            _index = min;");

        for (var i = 0; i < arity; i++)
            sb.AppendLine($"            _i{i + 1} = -1;");

        sb.AppendLine("            _entity = Entity.Invalid;");
        sb.AppendLine("        }");
        sb.AppendLine();

        // MoveNext
        sb.AppendLine("        public bool MoveNext()");
        sb.AppendLine("        {");
        sb.AppendLine("            while (--_index >= 0)");
        sb.AppendLine("            {");
        sb.AppendLine("                Entity e = Entity.Invalid;");
        sb.AppendLine();
        sb.AppendLine("                switch (_driver)");
        sb.AppendLine("                {");

        for (var driver = 1; driver <= arity; driver++)
        {
            sb.AppendLine($"                    case {driver}:");
            sb.AppendLine(
                $"                        e = _p{driver}.GetEntityAt(_index);"
            );
            sb.AppendLine(
                $"                        _i{driver} = _index;"
            );

            var checks = new StringBuilder();

            for (var i = 1; i <= arity; i++)
            {
                if (i == driver)
                    continue;

                if (checks.Length > 0)
                    checks.AppendLine(" ||");

                checks.Append(
                    $"                            !_p{i}.TryGetIndex(e, out _i{i})"
                );
            }

            if (checks.Length > 0)
            {
                sb.AppendLine($"                        if ({checks})");
                sb.AppendLine("                            continue;");
            }

            sb.AppendLine("                        break;");
        }

        sb.AppendLine("                }");
        sb.AppendLine();
        sb.AppendLine("                _entity = e;");
        sb.AppendLine("                return true;");
        sb.AppendLine("            }");
        sb.AppendLine();
        sb.AppendLine("            return false;");
        sb.AppendLine("        }");
        sb.AppendLine();

        // Current
        var currentArguments = new StringBuilder("_entity");

        for (var i = 0; i < arity; i++)
        {
            var index = i + 1;

            currentArguments.Append(
                $", ref _p{index}.GetAt(_i{index})"
            );
        }

        sb.AppendLine(
            $"        public QueryItem<{genericTypes}> Current =>"
        );
        sb.AppendLine($"            new({currentArguments});");

        sb.AppendLine("    }");
        sb.AppendLine("}");
        sb.AppendLine();

        // World factory method
        sb.AppendLine("public sealed partial class World");
        sb.AppendLine("{");

        sb.AppendLine(
            $"    public Query<{genericTypes}> Query<{genericTypes}>()"
        );
        AppendConstraints(sb, arity, "        ");
        sb.AppendLine(
            $"        => new({string.Join(", ", CreateGetPoolArguments(arity))});"
        );

        sb.AppendLine("}");

        return sb.ToString();
    }

    private static string[] CreateParameters(int arity)
    {
        var result = new string[arity];

        for (var i = 0; i < arity; i++)
            result[i] = $"ref T{i + 1} c{i + 1}";

        return result;
    }

    private static string[] CreatePoolParameters(int arity)
    {
        var result = new string[arity];

        for (var i = 0; i < arity; i++)
            result[i] = $"ComponentPool<T{i + 1}> p{i + 1}";

        return result;
    }

    private static string[] CreatePoolArguments(int arity)
    {
        var result = new string[arity];

        for (var i = 0; i < arity; i++)
            result[i] = $"_p{i + 1}";

        return result;
    }

    private static string[] CreateGetPoolArguments(int arity)
    {
        var result = new string[arity];

        for (var i = 0; i < arity; i++)
            result[i] = $"GetPool<T{i + 1}>()";
    
        return result;
    }

    private static string CreateMinCountExpression(int arity)
    {
        var expression = $"_p{arity}.Count";

        for (var i = arity - 1; i >= 1; i--)
            expression = $"int.Min(_p{i}.Count, {expression})";

        return expression;
    }
    
    private static void AppendConstraints(
        StringBuilder sb,
        int arity,
        string indent = "    ")
    {
        for (var i = 0; i < arity; i++)
            sb.AppendLine($"{indent}where T{i + 1} : struct");
    }
}
